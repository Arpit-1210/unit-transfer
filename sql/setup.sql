-- Unit Transfer app: tables, open access policies, units and the product sheet.
-- Run this ONCE in Supabase -> SQL Editor. Safe to run again.

create table if not exists ut_units (
  id uuid primary key default gen_random_uuid(),
  name text unique not null
);

create table if not exists ut_products (
  sno int primary key,          -- S.NO from the product sheet
  name text not null,
  rate numeric not null default 0,
  active boolean not null default true
);

create table if not exists ut_transfers (
  id uuid primary key default gen_random_uuid(),
  transfer_no text unique not null,
  transfer_date date not null,
  from_unit text not null,
  to_unit text not null,
  vehicle_type text,
  vehicle_no text,
  driver text,
  note text,
  total_qty numeric not null default 0,
  status text not null default 'done',
  created_at timestamptz not null default now()
);

create table if not exists ut_items (
  id uuid primary key default gen_random_uuid(),
  transfer_id uuid not null references ut_transfers(id) on delete cascade,
  sno int,
  product_name text not null,
  quantity numeric not null,
  position int not null default 1
);

create index if not exists ut_items_transfer on ut_items(transfer_id);
create index if not exists ut_transfers_date on ut_transfers(transfer_date desc);

alter table ut_units enable row level security;
alter table ut_products enable row level security;
alter table ut_transfers enable row level security;
alter table ut_items enable row level security;

drop policy if exists "open access" on ut_units;
drop policy if exists "open access" on ut_products;
drop policy if exists "open access" on ut_transfers;
drop policy if exists "open access" on ut_items;
create policy "open access" on ut_units for all using (true) with check (true);
create policy "open access" on ut_products for all using (true) with check (true);
create policy "open access" on ut_transfers for all using (true) with check (true);
create policy "open access" on ut_items for all using (true) with check (true);

grant all on ut_units, ut_products, ut_transfers, ut_items to anon, authenticated;

